valorDeA = float(input("Qual é o valor de A na equação do seguno grau: "))
valorDeB = float(input("Qual é o valor de B na equação do segundo grau: "))
valorDeC = float(input("Qual é o valor de C na equação do segundo grau: "))

delta = (valorDeB)**2 - 4 * valorDeA * valorDeC

print(f"Ovalor de Delta é {delta}")